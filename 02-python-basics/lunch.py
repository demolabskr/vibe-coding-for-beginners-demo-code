import random

menus = {
    ("좋음", "맑음"): ["비빔밥", "샐러드", "냉면", "김밥"],
    ("좋음", "비"): ["파전", "칼국수", "수제비"],
    ("보통", "맑음"): ["돈가스", "제육볶음", "쌀국수"],
    ("보통", "비"): ["짬뽕", "순두부찌개", "우동"],
    ("나쁨", "맑음"): ["떡볶이", "햄버거", "마라탕"],
    ("나쁨", "비"): ["김치찌개", "부대찌개", "라면"],
}

mood = input("오늘 기분은? (좋음/보통/나쁨) ").strip()
weather = input("오늘 날씨는? (맑음/비) ").strip()

if (mood, weather) in menus:
    choice = random.choice(menus[(mood, weather)])
    print("오늘 점심은 " + choice + " 어떠세요?")
elif mood not in ("좋음", "보통", "나쁨"):
    print("기분은 좋음, 보통, 나쁨 가운데 하나로 입력해 주세요.")
else:
    print("날씨는 맑음이나 비로 입력해 주세요.")
